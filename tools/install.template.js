/*
 * KB Tree Navigation - installer
 * --------------------------------------------------------------------------
 * Run in System Definition > Scripts - Background (scope: global),
 * ideally with a dedicated update set selected so the records can be moved.
 *
 * Creates or updates:
 *   - widgets  kb-tree-navigation (+ Angular ng-template kbtree-node.html)
 *              kb-selector
 *   - pages    kb_tree_home     (knowledge base list)
 *              kb_tree_article  (tree on the left, article on the right)
 *   - optional menu item in a portal header menu
 *
 * Safe to run more than once: widgets are updated in place, pages and the
 * menu item are only created when they do not exist yet.
 * Generated by tools/build_install.py - edit the files in widgets/ instead.
 */
(function () {
	var CONFIG = {
		homePage: 'kb_tree_home',
		articlePage: 'kb_tree_article',
		// Header menu that receives a "Knowledge bases" entry.
		// Employee Center: 'Employee Center Menu'. Service Portal (/sp): 'SP Header Menu'.
		// Leave empty to skip the menu item.
		menuTitle: 'Employee Center Menu',
		menuLabel: 'Knowledge bases',
		menuOrder: 50
	};

	var TREE_WIDGET = /*@TREE_WIDGET@*/null;
	var SELECTOR_WIDGET = /*@SELECTOR_WIDGET@*/null;
	var TREE_NODE_TEMPLATE = /*@TREE_NODE_TEMPLATE@*/null;

	function log(msg) { gs.info('[kb-tree-navigation] ' + msg); }

	// Insert or update the first record matching the encoded query.
	function upsert(table, encodedQuery, values) {
		var gr = new GlideRecord(table);
		gr.addEncodedQuery(encodedQuery);
		gr.setLimit(1);
		gr.query();
		var exists = gr.next();
		if (!exists)
			gr.initialize();
		for (var field in values)
			if (values.hasOwnProperty(field))
				gr.setValue(field, values[field]);
		var sysId = exists ? gr.update() : gr.insert();
		log((exists ? 'updated ' : 'created ') + table + ' ' + sysId);
		return sysId;
	}

	function findSysId(table, encodedQuery) {
		var gr = new GlideRecord(table);
		gr.addEncodedQuery(encodedQuery);
		gr.setLimit(1);
		gr.query();
		return gr.next() ? gr.getUniqueValue() : '';
	}

	function insert(table, values) {
		var gr = new GlideRecord(table);
		gr.initialize();
		for (var field in values)
			if (values.hasOwnProperty(field))
				gr.setValue(field, values[field]);
		return gr.insert();
	}

	// Page > container > row > columns > widget instances
	function createPage(id, title, columns) {
		if (findSysId('sp_page', 'id=' + id)) {
			log('page ' + id + ' already exists, layout left unchanged');
			return;
		}
		var page = insert('sp_page', { 'id': id, 'title': title, 'public': 'false' });
		var container = insert('sp_container', { sp_page: page, order: '1', width: 'container' });
		var row = insert('sp_row', { sp_container: container, order: '1' });
		for (var i = 0; i < columns.length; i++) {
			var col = insert('sp_column', { sp_row: row, order: String(i + 1), size: String(columns[i].size) });
			insert('sp_instance', {
				sp_column: col,
				sp_widget: columns[i].widget,
				order: '1',
				widget_parameters: JSON.stringify(columns[i].options || {})
			});
		}
		log('created page ' + id + ' (' + page + ')');
	}

	function opt(value) { return { value: value }; }

	// 1. Widgets
	var treeId = upsert('sp_widget', 'id=' + TREE_WIDGET.id, TREE_WIDGET);
	upsert('sp_ng_template', 'sp_widget=' + treeId + '^id=kbtree-node.html',
		{ sp_widget: treeId, id: 'kbtree-node.html', template: TREE_NODE_TEMPLATE });
	var selectorId = upsert('sp_widget', 'id=' + SELECTOR_WIDGET.id, SELECTOR_WIDGET);

	// 2. Out-of-the-box article content widget (Knowledge Management - Service Portal)
	var contentId = findSysId('sp_widget', 'id=kb-article-content');
	if (!contentId) {
		gs.error('[kb-tree-navigation] widget kb-article-content not found: is the Knowledge Management Service Portal plugin active?');
		return;
	}

	// 3. Pages
	createPage(CONFIG.homePage, 'Knowledge bases', [
		{ size: 12, widget: selectorId, options: { article_page: opt(CONFIG.articlePage) } }
	]);
	createPage(CONFIG.articlePage, 'Knowledge article', [
		{ size: 3, widget: treeId, options: { article_page: opt(CONFIG.articlePage), home_page: opt(CONFIG.homePage) } },
		{ size: 9, widget: contentId }
	]);

	// 4. Optional header menu entry
	if (CONFIG.menuTitle) {
		var menuId = findSysId('sp_instance_menu', 'title=' + CONFIG.menuTitle);
		if (!menuId) {
			gs.warn('[kb-tree-navigation] menu "' + CONFIG.menuTitle + '" not found, menu item skipped');
		} else if (findSysId('sp_rectangle_menu_item', 'sp_rectangle_menu=' + menuId + '^label=' + CONFIG.menuLabel)) {
			log('menu item already exists');
		} else {
			insert('sp_rectangle_menu_item', {
				sp_rectangle_menu: menuId, label: CONFIG.menuLabel, type: 'url',
				url: '?id=' + CONFIG.homePage, order: String(CONFIG.menuOrder), active: 'true'
			});
			log('created menu item "' + CONFIG.menuLabel + '" in ' + CONFIG.menuTitle);
		}
	}
	log('done');
})();
